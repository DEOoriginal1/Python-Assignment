day_of_the_week = int(input("Enter an Integer: "))

if day_of_the_week % 7 == 0:
    print("Sunday")
elif day_of_the_week % 7 == 1:
    print("Monday")
elif day_of_the_week % 7 == 2:
    print("Tuesday")
elif day_of_the_week % 7 == 3:
    print("Wednesday")
elif day_of_the_week % 7 == 4:
    print("Thursday")
elif day_of_the_week % 7 == 5:
    print("Friday")
else:
    print("Saturday")
    
    
